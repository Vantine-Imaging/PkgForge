import Foundation

/// Builds the `preinstall` and `postinstall` scripts that ship inside the
/// package (sections 5 and 6).
///
/// Every interpolated value goes through `ShellEscape` (S-13). Every binary is
/// invoked by absolute path (S-1) — a preinstall script runs as root, from an
/// installer environment whose `PATH` is not yours.
struct ScriptGenerator: Sendable {
    let bundle: AppBundle
    let configuration: PackageConfiguration
    let generatedAt: Date

    init(bundle: AppBundle, configuration: PackageConfiguration, generatedAt: Date = Date()) {
        self.bundle = bundle
        self.configuration = configuration
        self.generatedAt = generatedAt
    }

    private var timestamp: String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.timeZone = .current
        formatter.dateFormat = "yyyy-MM-dd HH:mm:ss"
        return formatter.string(from: generatedAt)
    }

    private var installLocation: String {
        let trimmed = configuration.installLocation.trimmingCharacters(in: .whitespaces)
        guard trimmed.count > 1, trimmed.hasSuffix("/") else { return trimmed }
        return String(trimmed.dropLast())
    }

    /// The path the app runs from, used to build the `pgrep -f` pattern (S-2).
    private var runningAppPath: String {
        "\(installLocation)/\(bundle.onDiskName).app"
    }

    private func header(_ role: String) -> String {
        var text = """
            #!/bin/bash
            #
            # \(role) — generated by PkgForge on \(timestamp)
            #
            #   App:        \(bundle.onDiskName).app (\(bundle.displayName))
            #   Identifier: \(configuration.identifier)
            #   Version:    \(configuration.version)
            #
            # Runs as root during installation. Output lands in /var/log/install.log.
            """

        let helpers = configuration.extraScriptURLs.map(\.lastPathComponent)
        if !helpers.isEmpty {
            text += """

                #
                # Bundled alongside this script, in the same directory:
                #   \(helpers.joined(separator: ", "))
                # Reach them as "$(/usr/bin/dirname "$0")/<name>". macOS does not
                # run them on its own — only preinstall and postinstall are
                # declared as script phases in the package.
                """
        }

        text += "\nset -u"
        return text
    }

    /// Splices the operator's own bash in verbatim. It is code, not data, so it
    /// is deliberately not escaped — `PackageBuilder` runs `bash -n` over the
    /// finished script instead, so a stray quote fails the build rather than
    /// the install.
    private func fragment(_ body: String, label: String) -> String {
        """
        # -------------------------------------------------- custom \(label)
        log "Running custom \(label) steps"
        \(body.trimmingCharacters(in: .newlines))
        log "Custom \(label) steps complete"

        """
    }

    private func preamble() -> String {
        """
        readonly APP_NAME=\(ShellEscape.singleQuoted(bundle.onDiskName))
        readonly BUNDLE_ID=\(ShellEscape.singleQuoted(configuration.identifier))
        readonly INSTALL_LOCATION=\(ShellEscape.singleQuoted(installLocation))

        # $3 is the target volume. It is / for every normal install; honouring
        # it keeps the scripts correct when someone targets another disk.
        TARGET_VOLUME="${3:-/}"
        readonly APP_PATH="${TARGET_VOLUME%/}${INSTALL_LOCATION}/${APP_NAME}.app"

        log() {
          /bin/echo "$(/bin/date '+%Y-%m-%d %H:%M:%S') PkgForge: $*"
        }
        """
    }

    // MARK: - preinstall

    func preinstall() -> String {
        let rootPaths = configuration.resolvedRootPaths(for: bundle)
        let userPaths = configuration.resolvedUserPaths(for: bundle)

        var script = header("preinstall")
        script += "\n\n"
        script += preamble()
        script += "\n\n"

        script += """
        readonly QUIT_TIMEOUT=\(max(0, configuration.quitTimeout))
        readonly ABORT_IF_RUNNING=\(configuration.abortIfRunning ? 1 : 0)

        # The app is matched by the executable path it was launched from, not by
        # process name: `pgrep -x` truncates at 15 characters and collides
        # between apps that share a name (S-2).
        readonly PROCESS_MATCH=\(ShellEscape.singleQuoted(ShellEscape.regexLiteral(runningAppPath + "/Contents/MacOS/")))

        log "Starting preinstall for ${APP_NAME}.app (${BUNDLE_ID})"

        app_is_running() {
          /usr/bin/pgrep -f "$PROCESS_MATCH" >/dev/null 2>&1
        }

        remove_path() {
          target="$1"
          if [ -e "$target" ] || [ -L "$target" ]; then
            if /bin/rm -rf "$target"; then
              log "Removed $target"
            else
              log "WARNING: could not remove $target"
            fi
          else
            log "Not present: $target"
          fi
        }

        # Every local account's uid. A LaunchAgent has to be booted out of each
        # GUI session it is loaded in, and with fast user switching that is not
        # only the console user's. Booting out a session that does not exist
        # fails harmlessly, which is cheaper than trying to enumerate them.
        all_user_uids() {
          for uid_home in /Users/*; do
            [ -d "$uid_home" ] || continue
            uid_name="$(/usr/bin/basename "$uid_home")"
            case "$uid_name" in
              Shared|Guest|.*) continue ;;
            esac
            uid_value="$(/usr/bin/id -u "$uid_name" 2>/dev/null)" || continue
            [ -n "$uid_value" ] && /bin/echo "$uid_value"
          done
        }

        # A LaunchDaemon or LaunchAgent still loaded when its plist disappears
        # keeps running, and launchd will not pick up the replacement (S-7).
        #
        # $2 is the uid to unload a LaunchAgent from. Omitted — for an agent in
        # /Library/LaunchAgents, which loads for everyone — it is tried for
        # every account.
        bootout_launch_job() {
          plist_path="$1"
          agent_uid="${2:-}"
          case "$plist_path" in
            *.plist) ;;
            *) return 0 ;;
          esac
          [ -f "$plist_path" ] || return 0

          label="$(/usr/libexec/PlistBuddy -c 'Print :Label' "$plist_path" 2>/dev/null)" || label=""
          if [ -z "$label" ]; then
            label="$(/usr/bin/basename "$plist_path" .plist)"
          fi

          case "$plist_path" in
            */LaunchDaemons/*)
              if /bin/launchctl bootout "system/$label" 2>/dev/null; then
                log "Unloaded LaunchDaemon $label"
              fi
              ;;
            */LaunchAgents/*)
              if [ -n "$agent_uid" ]; then
                if /bin/launchctl bootout "gui/$agent_uid/$label" 2>/dev/null; then
                  log "Unloaded LaunchAgent $label for uid $agent_uid"
                fi
              else
                for candidate_uid in $(all_user_uids); do
                  if /bin/launchctl bootout "gui/$candidate_uid/$label" 2>/dev/null; then
                    log "Unloaded LaunchAgent $label for uid $candidate_uid"
                  fi
                done
              fi
              ;;
          esac
        }

        # ---------------------------------------------------------------- user
        # A graceful quit has to be asked for as the logged-in user; root has no
        # session to send the Apple event from (S-3).
        CONSOLE_USER="$(/usr/bin/stat -f%Su /dev/console 2>/dev/null)" || CONSOLE_USER=""
        CONSOLE_UID=""
        if [ -n "$CONSOLE_USER" ] && [ "$CONSOLE_USER" != "root" ] && [ "$CONSOLE_USER" != "loginwindow" ]; then
          CONSOLE_UID="$(/usr/bin/id -u "$CONSOLE_USER" 2>/dev/null)" || CONSOLE_UID=""
          log "Console user: $CONSOLE_USER (uid ${CONSOLE_UID:-unknown})"
        else
          log "No console user session — skipping the graceful quit step."
        fi

        """

        if configuration.hasCustomPreinstall, configuration.customPreinstallPlacement == .first {
            script += fragment(configuration.customPreinstall, label: "preinstall")
        }

        script += """
        # ------------------------------------------------------------- stop app
        if app_is_running; then
          log "${APP_NAME}.app is running."

          if [ -n "$CONSOLE_UID" ]; then
            log "Requesting a graceful quit as $CONSOLE_USER."
            /bin/launchctl asuser "$CONSOLE_UID" /usr/bin/sudo -u "$CONSOLE_USER" \\
              /usr/bin/osascript -e \(ShellEscape.singleQuoted("tell application id \"\(ShellEscape.appleScriptLiteral(configuration.identifier))\" to quit")) \\
              >/dev/null 2>&1 || log "Quit request returned non-zero — continuing."
          fi

          waited=0
          while [ "$waited" -lt "$QUIT_TIMEOUT" ] && app_is_running; do
            /bin/sleep 1
            waited=$((waited + 1))
          done

          if app_is_running; then
            log "Still running after ${waited}s — sending SIGTERM."
            /usr/bin/pkill -f "$PROCESS_MATCH" 2>/dev/null || true
            /bin/sleep 5
          else
            log "Quit cleanly after ${waited}s."
          fi

          if app_is_running; then
            log "Still running after SIGTERM — sending SIGKILL."
            /usr/bin/pkill -9 -f "$PROCESS_MATCH" 2>/dev/null || true
            /bin/sleep 2
          fi

          if app_is_running; then
            if [ "$ABORT_IF_RUNNING" -eq 1 ]; then
              log "ERROR: ${APP_NAME}.app could not be stopped. Aborting the install."
              log "ERROR: replacing a bundle that is still mapped into a running process leaves it half-broken."
              exit 1
            else
              log "WARNING: ${APP_NAME}.app could not be stopped. Continuing anyway."
            fi
          fi
        else
          log "${APP_NAME}.app is not running."
        fi

        """

        // S-7 — unload before anything is deleted underneath launchd.
        if rootPaths.isEmpty {
            script += """
            # ------------------------------------------------------- launch jobs
            # No root-level cleanup paths configured.

            """
        } else {
            script += """
            # ------------------------------------------------------- launch jobs
            ROOT_STALE_PATHS=(
            \(rootPaths.map { "  " + ShellEscape.singleQuoted($0) }.joined(separator: "\n"))
            )

            for stale in "${ROOT_STALE_PATHS[@]}"; do
              bootout_launch_job "$stale"
            done

            """
        }

        script += """
        # ------------------------------------------------------- existing copy
        if [ -d "$APP_PATH" ]; then
          log "Removing the existing bundle at $APP_PATH"
          remove_path "$APP_PATH"
        else
          log "No existing bundle at $APP_PATH"
        fi

        """

        if configuration.removeStrayCopies {
            script += """
            # ------------------------------------------------------ stray copies
            # Matched on filename, so the identifier is checked before anything
            # is deleted — two unrelated vendors ship a "Console.app".
            stray_is_same_app() {
              stray_plist="$1/Contents/Info.plist"
              [ -f "$stray_plist" ] || return 1
              stray_id="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$stray_plist" 2>/dev/null)" || stray_id=""
              [ "$stray_id" = "$BUNDLE_ID" ]
            }

            log "Searching for stray copies of ${APP_NAME}.app"
            while IFS= read -r stray; do
              [ -n "$stray" ] || continue
              [ "$stray" = "$APP_PATH" ] && continue
              if stray_is_same_app "$stray"; then
                log "Found a stray copy at $stray"
                remove_path "$stray"
              else
                log "Skipping $stray — different bundle identifier, not ours"
              fi
            done < <(/usr/bin/find /Applications /Users/*/Applications -maxdepth 2 \\
              -name \(ShellEscape.singleQuoted(ShellEscape.globLiteral(bundle.onDiskName) + ".app")) 2>/dev/null)

            """
        }

        if rootPaths.isEmpty {
            script += """
            # -------------------------------------------------- root-level paths
            # Nothing configured.

            """
        } else {
            script += """
            # -------------------------------------------------- root-level paths
            for stale in "${ROOT_STALE_PATHS[@]}"; do
              remove_path "$stale"
            done

            """
        }

        if userPaths.isEmpty {
            script += """
            # ----------------------------------------------------- per-user paths
            # Nothing configured.

            """
        } else {
            script += """
            # ----------------------------------------------------- per-user paths
            USER_STALE_PATHS=(
            \(userPaths.map { "  " + ShellEscape.singleQuoted($0) }.joined(separator: "\n"))
            )

            for home in /Users/*; do
              [ -d "$home" ] || continue
              home_name="$(/usr/bin/basename "$home")"
              case "$home_name" in
                Shared|Guest|.*) continue ;;
              esac
              home_uid="$(/usr/bin/id -u "$home_name" 2>/dev/null)" || home_uid=""

              for relative in "${USER_STALE_PATHS[@]}"; do
                bootout_launch_job "$home/$relative" "$home_uid"
                remove_path "$home/$relative"
              done
            done

            """
        }

        if configuration.hasCustomPreinstall, configuration.customPreinstallPlacement == .last {
            script += fragment(configuration.customPreinstall, label: "preinstall")
        }

        script += """
        log "preinstall complete."
        exit 0

        """

        return script
    }

    /// With relocation pinned off the payload can only land at `$APP_PATH`, so
    /// its absence means ownership was never corrected on a bundle in
    /// `/Applications` — the exact case the chown exists to close, and worth
    /// failing the policy over. If the operator has deliberately allowed
    /// relocation, the bundle being elsewhere is expected and failing would be
    /// wrong.
    private var missingBundleHandling: String {
        if configuration.preventRelocation {
            return """
              log "ERROR: expected the installed bundle at $APP_PATH but it is not there."
              exit 1
            """
        }
        return """
              log "WARNING: no bundle at $APP_PATH. Relocation is allowed for this package, so"
              log "WARNING: the installer may have placed it elsewhere. Ownership was NOT corrected."
              exit 0
            """
    }

    // MARK: - postinstall

    func postinstall() -> String {
        var script = header("postinstall")
        script += "\n\n"
        script += preamble()
        script += "\n\n"

        script += """
        log "Starting postinstall for ${APP_NAME}.app"

        if [ ! -d "$APP_PATH" ]; then
        \(missingBundleHandling)
        fi

        # A bundle in /Applications owned by anyone but root is a
        # privilege-escalation path: any local user could swap the binary (S-14).
        if /usr/sbin/chown -R root:wheel "$APP_PATH"; then
          log "Set ownership to root:wheel"
        else
          log "WARNING: chown failed on $APP_PATH"
        fi

        if /bin/chmod -R go-w "$APP_PATH"; then
          log "Removed group/other write permissions"
        else
          log "WARNING: chmod failed on $APP_PATH"
        fi

        # Installer payloads are not quarantined, but the attribute can ride
        # along from the machine the package was built on (S-16).
        if /usr/bin/xattr -dr com.apple.quarantine "$APP_PATH" 2>/dev/null; then
          log "Cleared com.apple.quarantine"
        fi

        """

        if configuration.hasCustomPostinstall {
            script += fragment(configuration.customPostinstall, label: "postinstall")
        }

        script += """
        # Advisory only — an unsigned in-house build is a legitimate payload (S-17).
        if /usr/bin/codesign --verify --deep --strict "$APP_PATH" 2>/dev/null; then
          log "Code signature verified"
        else
          log "WARNING: code signature did not verify. The app is installed; check it before deploying widely."
        fi

        log "postinstall complete."
        exit 0

        """

        return script
    }
}
